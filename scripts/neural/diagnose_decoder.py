"""Is short-possession recall limited by the network or by the decoder? EXTERNAL VALIDATION only.

For the cached validation log-probabilities of a run (written by ``error_analysis.py``), compare:

- **raw argmax** — per-frame most likely class, no switching constraint;
- **Viterbi** at the run's selected penalties and over a grid of lower team-switch penalties;

and report, pooled over validation matches (mean per match): spellF1; spell recall at IoU 0.5 by
true duration (< 2 s, 2–5 s, ≥ 5 s); spell precision; transition precision / recall within
±0.5 s; false transitions per alive minute; H/A/D macroF1 and D F1; team accuracy on alive frames
with the ball seen vs unseen. A second table asks whether the *raw* probabilities contain
evidence for each true < 2 s possession (share of its frames whose argmax is the true team).

Test matches and the challenge game are never read. Output: ``experiments/research/neural/DECODER_DIAGNOSTIC.md``.

Usage::

    python scripts/neural/diagnose_decoder.py --runs n008_n007_seed2 n011_n010_seed2
"""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

import numpy as np  # noqa: E402

from possession_lab.neural.canonical import A, CanonicalMatch, D, H  # noqa: E402
from possession_lab.neural.data import degrade_match  # noqa: E402
from possession_lab.neural.decode import DecodeConfig, decode_match  # noqa: E402
from possession_lab.neural.external_eval import official_metrics  # noqa: E402

FPS = 25
TOL = 12  # official transition tolerance (frames), ±0.48 s
BINS = [("< 2 s", 0, 2), ("2–5 s", 2, 5), ("≥ 5 s", 5, 1e9)]
TEAM_GRID = (0.5, 1.0, 2.0, 4.0, 8.0)


def argmax_decode(lp: np.ndarray, period: np.ndarray) -> np.ndarray:
    """Per-frame argmax over (H, A, D); gap frames X (as ``decode_match``)."""
    return decode_match(lp, period, DecodeConfig(0.0, 0.0))  # zero penalties == argmax


def metrics(gt: np.ndarray, pred: np.ndarray, ball_seen: np.ndarray) -> dict[str, float]:
    """Diagnostic metrics for one match (official helpers only)."""
    m = official_metrics()
    runs = m.valid_runs(gt)
    pf = m.fill_abstentions(pred, runs)
    out: dict[str, float] = {"spell_f1": float(m.spell_scores(gt, pf, runs)["mean_f1"])}
    gs, ps = m.possession_spells(gt, runs), m.possession_spells(pf, runs)
    flags = m.matched_gt_flags(m.spell_overlaps(gs, ps), len(gs), 0.5)
    dur = np.array([(b - a) / FPS for a, b, _ in gs])
    for name, lo, hi in BINS:
        sel = (dur >= lo) & (dur < hi)
        out[f"recall {name}"] = float(flags[sel].mean()) if sel.any() else float("nan")
    out["spell precision"] = float(flags.sum() / max(len(ps), 1))
    out["pred / true spells"] = len(ps) / max(len(gs), 1)
    tr = m.transition_scores(m.transitions(gt, runs), m.transitions(pf, runs), TOL)
    out["transition P"] = tr["precision"]
    out["transition R"] = tr["recall"]
    alive_min = float(np.isin(gt, (H, A)).sum()) / FPS / 60
    out["false transitions / min"] = tr["n_spurious"] / max(alive_min, 1e-9)
    cm3 = m.scored_confusion(m.confusion(gt, pf))
    out["macroF1"] = m.macro_f1(cm3)
    out["D F1"] = m.per_class_prf(cm3, D)[2]
    alive = np.isin(gt, (H, A))
    for name, mask in (
        ("team acc ball seen", alive & ball_seen),
        ("team acc ball unseen", alive & ~ball_seen),
    ):
        out[name] = float((pf[mask] == gt[mask]).mean()) if mask.any() else float("nan")
    return out


def short_evidence(gt: np.ndarray, raw: np.ndarray, lp: np.ndarray) -> list[tuple[float, float]]:
    """Per true < 2 s possession: (share of frames with raw argmax = true team, mean p(true))."""
    m = official_metrics()
    runs = m.valid_runs(gt)
    out = []
    for a, b, k in m.possession_spells(gt, runs):
        if b - a < 2 * FPS:
            out.append((float((raw[a:b] == k).mean()), float(np.exp(lp[a:b, k]).mean())))
    return out


def mean_dict(rows: list[dict[str, float]]) -> dict[str, float]:
    """Average each diagnostic metric across the match-level result rows."""
    return {k: float(np.nanmean([r[k] for r in rows])) for k in rows[0]}


def main() -> int:
    """Compare decoder variants using cached external validation predictions only."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--runs", nargs="+", required=True)
    parser.add_argument(
        "--report", type=Path, default=ROOT / "experiments/research/neural/DECODER_DIAGNOSTIC.md"
    )
    args = parser.parse_args()
    args.report = args.report.resolve()

    lines = [
        "# Decoder vs model diagnostic — external validation matches only",
        "",
        "Generated by `scripts/neural/diagnose_decoder.py` from cached validation "
        "log-probabilities. Metrics are means over validation matches. Recall / precision "
        f"of spells at IoU 0.5; transitions within ±{TOL} frames (±{TOL / FPS:.2f} s). "
        "Test matches and the challenge game are not read.",
        "",
    ]
    for run in args.runs:
        run_dir = ROOT / "artifacts" / "neural" / "runs" / run
        cfg = tomllib.loads((run_dir / "config.toml").read_text())
        sel = json.loads((run_dir / "external_eval.json").read_text())["decoder"]
        cache = np.load(run_dir / "val_logp.npz")
        canon = ROOT / cfg["data"]["canonical_dir"]
        clean = [CanonicalMatch.load(canon / f"{n}.npz") for n in cfg["data"]["val"]]
        seed = cfg["data"]["degrade_eval_seed"]
        conds = {"clean": clean, "degraded": [degrade_match(mm, seed) for mm in clean]}
        decoders = [("raw argmax", None)]
        gain = sel.get("transition_gain", 0.0)
        decoders.append(
            (
                f"Viterbi selected (team {sel['team_switch']:g} / dead "
                f"{sel['dead_switch']:g} / gain {gain:g})",
                DecodeConfig(sel["team_switch"], sel["dead_switch"], gain),
            )
        )
        if gain:
            decoders.append(
                (
                    f"Viterbi team {sel['team_switch']:g} / dead {sel['dead_switch']:g} / gain 0",
                    DecodeConfig(sel["team_switch"], sel["dead_switch"]),
                )
            )
        decoders += [
            (
                f"Viterbi team {t:g} / dead {sel['dead_switch']:g} / gain {gain:g}",
                DecodeConfig(t, sel["dead_switch"], gain),
            )
            for t in TEAM_GRID
            if t != sel["team_switch"]
        ]
        lines += [f"## `{run}`", ""]
        for cond, matches in conds.items():
            table: dict[str, dict[str, float]] = {}
            evidence: list[tuple[float, float]] = []
            for name, dec in decoders:
                rows = []
                for mm in matches:
                    lp = cache[f"{cond}:{mm.match_id}"]
                    pred = (
                        argmax_decode(lp, mm.period)
                        if dec is None
                        else decode_match(lp, mm.period, dec)
                    )
                    rows.append(metrics(mm.labels, pred, ~np.isnan(mm.ball[:, 0])))
                    if dec is None:
                        evidence += short_evidence(mm.labels, pred, lp)
                table[name] = mean_dict(rows)
            keys = list(next(iter(table.values())))
            lines += [
                f"### {cond}",
                "",
                "| decoder | " + " | ".join(keys) + " |",
                "|---" * (len(keys) + 1) + "|",
            ]
            for name, row in table.items():
                lines.append(f"| {name} | " + " | ".join(f"{row[k]:.3f}" for k in keys) + " |")
            share = np.array([e[0] for e in evidence])
            prob = np.array([e[1] for e in evidence])
            lines += [
                "",
                f"**Raw evidence for true < 2 s possessions ({cond}, n = {len(share)})**:"
                f" share of their frames whose raw argmax is the true team — mean "
                f"{share.mean():.2f}; ≥ 50 % of frames for {(share >= 0.5).mean():.0%} of "
                f"them, any frame for {(share > 0).mean():.0%}, none for "
                f"{(share == 0).mean():.0%}. Mean p(true team) inside them "
                f"{prob.mean():.2f}.",
                "",
            ]
    args.report.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"report: {args.report.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
